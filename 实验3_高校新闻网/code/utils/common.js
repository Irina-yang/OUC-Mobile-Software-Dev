function getNewsList(category = '全部') {
  let list = [];
  for (let i = 0; i < news.length; i++) {
    if (category === '全部' || news[i].category === category) {
      list.push({
        id: news[i].id,
        title: news[i].title,
        poster: news[i].poster,
        add_date: news[i].add_date,
        category: news[i].category
      });
    }
  }
  return list;
}

function getNewsDetail(newsID) {
  let msg = { code: '404', news: {} };
  for (let i = 0; i < news.length; i++) {
    if (newsID === news[i].id) {
      msg.code = '200';
      msg.news = news[i];
      break;
    }
  }
  return msg;
}

